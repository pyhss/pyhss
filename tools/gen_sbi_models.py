"""Generate the pydantic v2 SBI models in lib/sbi/models/ from the vendored 3GPP specs.

The schemas listed in specs/3gpp/<release>/PyHSS_SBI_Models.yaml are generated, together with
every schema they reference, by datamodel-code-generator. The generator must be the pinned
version from requirements-dev.txt, so that regenerating gives the same output.

The generator does not cope with the full 3GPP spec set: it loads entire referenced files,
which pulls in hundreds of OAM schemas, and it fails on some 3GPP constructs. So this script
first builds a temporary bundle:

 * The schema-level closure of the root schemas is copied into one self-contained document,
   and all $refs are rewritten to local ones. Pure alias schemas ({$ref: X}) are collapsed to
   their target. Names that are defined differently in several files get a "_TSxxxxx" suffix,
   except the TS29571 (common data) definition, which keeps the plain name.
 * Constraint-only alternatives are removed: anyOf/oneOf/allOf entries that contain nothing
   but keywords like "required" or "not", e.g. NFProfile: anyOf: [{required: [fqdn]},
   {required: [ipv4Addresses]}]. pydantic models cannot express these.
 * An allOf of value constraints only (e.g. Ipv6Addr: two patterns) is merged into the parent
   schema. If a keyword occurs twice, the first one is kept, e.g. the stricter RFC 5952 pattern.

The vendored spec files are not modified. The tests validate PyHSS's requests and responses
against them, including the constraints that are left out of the models.

Usage: tools/gen_sbi_models.py [--out lib/sbi/models]
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import threading

import yaml

GENERATOR_VERSION = "0.86.0"
SPEC_RELEASE = "r19-20260402"
CONSTRAINT_KEYS = {"required", "not", "minProperties", "maxProperties"}
VALUE_KEYS = {"pattern", "minLength", "maxLength", "minimum", "maximum", "format"}

top_dir = os.path.realpath(os.path.join(os.path.dirname(__file__), ".."))
spec_dir = os.path.join(top_dir, "specs/3gpp", SPEC_RELEASE)
root_spec = "PyHSS_SBI_Models.yaml"
default_out = os.path.join(top_dir, "lib/sbi/models")

HEADER = f"""# Generated by tools/gen_sbi_models.py (datamodel-code-generator {GENERATOR_VERSION}) - DO NOT EDIT.
# Source: specs/3gpp/{SPEC_RELEASE}/ - 3GPP 5GC OpenAPI specifications,
# (c) 3GPP Organizational Partners (ARIB, ATIS, CCSA, ETSI, TSDSI, TTA, TTC)."""


def is_constraint_only(node):
    return isinstance(node, dict) and node and set(node) <= CONSTRAINT_KEYS


def is_value_constraint_only(node):
    return isinstance(node, dict) and node and set(node) <= VALUE_KEYS


def strip_constraint_alternatives(node):
    if isinstance(node, dict):
        if isinstance(node.get("allOf"), list) and all(is_value_constraint_only(x) for x in node["allOf"]):
            # e.g. Ipv6Addr: {type: string, allOf: [{pattern: A}, {pattern: B}]}: merge into the
            # parent schema; for repeated keywords (two patterns) the first one is kept
            for item in node.pop("allOf"):
                for key, value in item.items():
                    node.setdefault(key, value)
        for key in ("anyOf", "oneOf", "allOf"):
            if isinstance(node.get(key), list):
                kept = [x for x in node[key] if not is_constraint_only(x)]
                if kept:
                    node[key] = kept
                else:
                    del node[key]
        for value in node.values():
            strip_constraint_alternatives(value)
    elif isinstance(node, list):
        for value in node:
            strip_constraint_alternatives(value)


class Bundler:
    def __init__(self):
        self.docs = {}
        self.keys = {}

    def load(self, name):
        if name not in self.docs:
            with open(os.path.join(spec_dir, name)) as f:
                self.docs[name] = yaml.safe_load(f)
        return self.docs[name]

    def schema(self, ident):
        name, schema = ident
        return self.load(name)["components"]["schemas"][schema]

    def parse_ref(self, ref, current):
        name, _, pointer = ref.partition("#")
        prefix = "/components/schemas/"
        if not pointer.startswith(prefix) or "/" in pointer[len(prefix) :]:
            sys.exit(f"Unsupported $ref in a schema: {ref} (in {current})")
        return (os.path.basename(name) if name else current, pointer[len(prefix) :])

    def collapse(self, ident):
        """Follow pure alias schemas ({$ref: X}) to the schema they point to."""
        seen = set()
        while True:
            node = self.schema(ident)
            if not (isinstance(node, dict) and set(node) == {"$ref"}):
                return ident
            if ident in seen:
                sys.exit(f"$ref loop at {ident}")
            seen.add(ident)
            ident = self.parse_ref(node["$ref"], ident[0])

    def refs(self, node, current, out):
        if isinstance(node, dict):
            for key, value in node.items():
                if key == "$ref" and isinstance(value, str):
                    out.append(self.collapse(self.parse_ref(value, current)))
                else:
                    self.refs(value, current, out)
        elif isinstance(node, list):
            for value in node:
                self.refs(value, current, out)

    def closure(self, roots):
        found = []
        pending = list(roots)
        while pending:
            ident = pending.pop(0)
            if ident in found:
                continue
            found.append(ident)
            refs = []
            self.refs(self.schema(ident), ident[0], refs)
            pending += refs
        return found

    def assign_keys(self, idents):
        by_name = {}
        for ident in idents:
            by_name.setdefault(ident[1], []).append(ident)
        for schema, owners in by_name.items():
            for ident in owners:
                if len(owners) == 1 or ident[0] == "TS29571_CommonData.yaml":
                    self.keys[ident] = schema
                else:
                    self.keys[ident] = f"{schema}_{ident[0].split('_')[0]}"

    def rewrite(self, node, current):
        if isinstance(node, dict):
            out = {}
            for key, value in node.items():
                if key == "$ref" and isinstance(value, str):
                    target = self.collapse(self.parse_ref(value, current))
                    out[key] = f"#/components/schemas/{self.keys[target]}"
                else:
                    out[key] = self.rewrite(value, current)
            return out
        if isinstance(node, list):
            return [self.rewrite(value, current) for value in node]
        return node

    def bundle(self):
        root = self.load(root_spec)
        roots = [self.collapse((root_spec, name)) for name in root["components"]["schemas"]]
        idents = self.closure(roots)
        self.assign_keys(idents)
        schemas = {}
        for ident in sorted(idents, key=lambda i: self.keys[i]):
            node = self.rewrite(self.schema(ident), ident[0])
            strip_constraint_alternatives(node)
            schemas[self.keys[ident]] = node
        return {
            "openapi": "3.0.0",
            "info": {"title": "PyHSS SBI models", "version": "1"},
            "paths": {},
            "components": {"schemas": schemas},
        }


def run_generator(args):
    from importlib.metadata import version as package_version

    from datamodel_code_generator.__main__ import main as codegen_main

    version = package_version("datamodel-code-generator")

    if version != GENERATOR_VERSION:
        sys.exit(f"datamodel-code-generator {GENERATOR_VERSION} required, found {version}")

    # The 3GPP schemas are deeply nested; the generator needs a large stack.
    sys.setrecursionlimit(100000)
    threading.stack_size(512 * 1024 * 1024)
    result = []
    thread = threading.Thread(target=lambda: result.append(codegen_main(args)))
    thread.start()
    thread.join()
    return result[0] if result else 1


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=default_out, help="output directory (default: %(default)s)")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        bundle = os.path.join(tmp, "bundle.yaml")
        gen = os.path.join(tmp, "models")
        with open(bundle, "w") as f:
            yaml.safe_dump(Bundler().bundle(), f, sort_keys=False, allow_unicode=True)
        ret = run_generator(
            [
                "--input",
                bundle,
                "--input-file-type",
                "openapi",
                "--output",
                gen,
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.11",
                "--use-annotated",
                "--field-constraints",
                "--use-double-quotes",
                "--capitalise-enum-members",
                "--use-subclass-enum",
                "--disable-timestamp",
                "--allow-population-by-field-name",
                "--formatters",
                "builtin",
                "--custom-file-header",
                HEADER,
            ]
        )
        if ret:
            sys.exit(f"datamodel-codegen failed ({ret})")
        if os.path.isfile(gen):
            # Single module output: turn it into a package
            os.rename(gen, gen + ".py")
            os.mkdir(gen)
            os.rename(gen + ".py", os.path.join(gen, "__init__.py"))
        shutil.rmtree(args.out, ignore_errors=True)
        shutil.copytree(gen, args.out)

    subprocess.run([sys.executable, "-m", "compileall", "-q", args.out], check=True)
    print(f"Generated models in {args.out}")


if __name__ == "__main__":
    main()
